// Backticks, single quotes, and double quotes in JavaScript

// Single quotes: used for simple strings, mostly similar to double quotes.
// Double quotes: also used for strings, common in JavaScript.
// Backticks: used for template literals; they allow variables inside ${}.

let name = "Ravi";

console.log('Hello ' + name);      // single quote
console.log("Hello " + name);      // double quote
console.log(`Hello ${name}`);       // backtick template literal

